const fs = require('fs');
const path = require('path');

function getCssFilesRecursively(dir) {
    let results = [];
    if (!fs.existsSync(dir)) return results;
    const list = fs.readdirSync(dir);
    list.forEach((file) => {
        const filePath = path.join(dir, file);
        const stat = fs.statSync(filePath);
        if (stat && stat.isDirectory()) {
            results = results.concat(getCssFilesRecursively(filePath));
        } else if (file.endsWith('.css')) {
            results.push(filePath);
        }
    });
    return results;
}

const editorCoreDir = path.resolve(__dirname, '..');
const srcDir = path.join(editorCoreDir, 'src');

const baseFiles = [
    path.join(srcDir, 'styles', 'editor.css'),
    path.join(srcDir, 'styles', 'highlight-theme.css'),
];

const extensionCssFiles = getCssFilesRecursively(path.join(srcDir, 'extensions'));

let combinedCss = '';

function appendFile(filePath) {
    if (fs.existsSync(filePath)) {
        const relativePath = path.relative(editorCoreDir, filePath);
        combinedCss += `/* Source: ${relativePath} */\n`;
        combinedCss += fs.readFileSync(filePath, 'utf8') + '\n\n';
    }
}

baseFiles.forEach(appendFile);
extensionCssFiles.forEach(appendFile);

const outputPath = path.join(srcDir, 'export', 'generated-styles.ts');
const fileContent = `// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-print-styles.cjs

export const GENERATED_CORE_STYLES = \`
${combinedCss.replace(/`/g, '\\`').replace(/\${/g, '\\${')}
\`;
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, fileContent, 'utf8');
console.log('✅ Print styles generated successfully at src/export/generated-styles.ts');
